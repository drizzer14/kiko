// The SF Symbol currency-sign glyph shown for each currency, keyed by its code.
// Mirrors src/holdings/entity-symbols.ts (the account Kind / holding Type
// symbol maps): a fixed UI glyph the currency ChipRow selects render before
// each option's label via ChipRow's `icons` prop. Distinct from currency.ts's
// `currencySymbol`, which is the plain Unicode sign (₴, $, €, ₿) used in
// formatted money text — this map is the SF Symbol *name* (hryvniasign,
// dollarsign, …) the native icon component renders.
//
// SF Symbols ships a dedicated currency-sign glyph for only a handful of
// currencies. The originally shipped set (UAH/USD/EUR/GBP/CHF/BTC) keeps its
// dedicated, on-device-proven signs; every additional fiat falls back to
// `banknote` — a generic money glyph already used elsewhere in the app
// (src/holdings) and available since iOS 15, comfortably below this app's iOS
// 16 minimum. The fallback is deliberate: an unverified, too-new per-currency
// SF Symbol renders BLANK on device, so a code without a proven sign uses the
// safe generic glyph rather than a guessed one.
//
// An exhaustive `Record`, not `Partial`: every `Currency` must supply a
// non-empty SF Symbol name, so adding a currency with no sign is a COMPILE
